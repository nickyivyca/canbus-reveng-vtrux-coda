package com.reverseit.p914

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The five cases in the B1 spec's degraded-states table, plus the two the table assumes cannot
 * happen (an unstamped DBC, a malformed stamp).
 *
 * Worth a unit test rather than an on-car check because four of the seven are states the car
 * cannot easily be put into: producing a real major mismatch means flashing deliberately stale
 * firmware, and "no beacon for ten seconds" means waiting out a timer with the wrong VCU
 * attached. A wrong verdict here fails in the direction that matters -- rendering plausible wrong
 * numbers instead of quarantining -- so it should not first be exercised in the car.
 */
class SchemaCheckTest {

    /** The real stamp, verbatim from the generated vcu.dbc. */
    private val realComment =
        "914 EV telemetry schema 3.0, SCHEMA_HASH=0x489360E3. " +
            "Generated by generate_914_dbc.py -- do not hand-edit."

    private val stamp = SchemaCheck.Stamp(major = 3, minor = 0, hash = 0x489360E3L)

    @Test
    fun `parses the stamp the generator actually emits`() {
        assertEquals(stamp, SchemaCheck.parseStamp(realComment))
    }

    @Test
    fun `an absent or unstamped comment yields no stamp`() {
        assertNull(SchemaCheck.parseStamp(null))
        assertNull(SchemaCheck.parseStamp("914 EV telemetry. Generated by generate_914_dbc.py."))
    }

    @Test
    fun `matching hash proceeds`() {
        val v = SchemaCheck.evaluate(stamp, SchemaCheck.Broadcast(3, 0, 0x489360E3L), 0)
        assertEquals(SchemaCheck.Verdict.Match(3, 0), v)
        assertEquals("SCHEMA 3.0 ok", SchemaCheck.bandText(v))
    }

    @Test
    fun `differing hash with the same major is additive, not fatal`() {
        val v = SchemaCheck.evaluate(stamp, SchemaCheck.Broadcast(3, 1, 0xDEADBEEFL), 0)
        assertTrue(v is SchemaCheck.Verdict.MinorDiffers)
        assertEquals("SCHEMA 3.1 +", SchemaCheck.bandText(v))
    }

    /**
     * The case that must not be got wrong. This is a real capture's schema: `serial-bringup.log`
     * was recorded against 2.0 / 0x505AA323, and replaying it against the 3.0 DBC has to
     * quarantine rather than decode.
     */
    @Test
    fun `differing major quarantines`() {
        val v = SchemaCheck.evaluate(stamp, SchemaCheck.Broadcast(2, 0, 0x505AA323L), 0)
        assertTrue(v is SchemaCheck.Verdict.Quarantine)
        assertEquals("SCHEMA 2.0 QUARANTINE", SchemaCheck.bandText(v))
    }

    @Test
    fun `no beacon is quiet inside the grace period and loud after it`() {
        assertEquals(
            SchemaCheck.Verdict.NotYetSeen,
            SchemaCheck.evaluate(stamp, null, 0),
        )
        assertEquals(
            SchemaCheck.Verdict.NotYetSeen,
            SchemaCheck.evaluate(stamp, null, SchemaCheck.BEACON_GRACE_MS - 1),
        )
        assertEquals(
            SchemaCheck.Verdict.NeverSeen,
            SchemaCheck.evaluate(stamp, null, SchemaCheck.BEACON_GRACE_MS),
        )
    }

    /**
     * Neither "cannot tell" state may blank the display. Blanking is reserved for a *confirmed*
     * mismatch, because "I know this is wrong" and "I cannot check" must not look alike.
     */
    @Test
    fun `only a confirmed major mismatch blanks the data region`() {
        val nonBlanking = listOf(
            SchemaCheck.evaluate(stamp, null, 0),
            SchemaCheck.evaluate(stamp, null, 60_000),
            SchemaCheck.evaluate(null, null, 60_000),
            SchemaCheck.evaluate(stamp, SchemaCheck.Broadcast(3, 0, 0x489360E3L), 0),
            SchemaCheck.evaluate(stamp, SchemaCheck.Broadcast(3, 9, 1L), 0),
        )
        for (v in nonBlanking) {
            assertTrue("$v must not blank", v !is SchemaCheck.Verdict.Quarantine)
        }
    }

    /** An unstamped DBC is a build problem, and must not masquerade as a missing beacon. */
    @Test
    fun `an unstamped DBC is its own verdict`() {
        val v = SchemaCheck.evaluate(null, SchemaCheck.Broadcast(3, 0, 0x489360E3L), 0)
        assertEquals(SchemaCheck.Verdict.DbcUnstamped, v)
    }

    @Test
    fun `broadcast is read only when all three signals are present`() {
        assertNull(SchemaCheck.readBroadcast(emptyMap()))
        assertNull(SchemaCheck.readBroadcast(mapOf("SchemaMajor" to 3.0, "SchemaMinor" to 0.0)))
        assertEquals(
            SchemaCheck.Broadcast(3, 0, 0x489360E3L),
            SchemaCheck.readBroadcast(
                mapOf(
                    "SchemaMajor" to 3.0,
                    "SchemaMinor" to 0.0,
                    "SchemaHash" to 0x489360E3L.toDouble(),
                ),
            ),
        )
    }

    /**
     * The top bit of the hash must survive the trip through the flat `Map<String, Double>` the
     * view model exposes. A 32-bit hash above 0x7FFFFFFF is unremarkable, and taking it through
     * Int anywhere would wrap it negative and turn every high-hash schema into a false mismatch.
     */
    @Test
    fun `a hash with the top bit set round-trips`() {
        val high = 0xF0000001L
        val highStamp = SchemaCheck.Stamp(3, 0, high)
        val observed = SchemaCheck.readBroadcast(
            mapOf(
                "SchemaMajor" to 3.0,
                "SchemaMinor" to 0.0,
                "SchemaHash" to high.toDouble(),
            ),
        )
        assertEquals(high, observed!!.hash)
        assertEquals(
            SchemaCheck.Verdict.Match(3, 0),
            SchemaCheck.evaluate(highStamp, observed, 0),
        )
        assertEquals(
            highStamp,
            SchemaCheck.parseStamp("914 EV telemetry schema 3.0, SCHEMA_HASH=0xF0000001."),
        )
    }
}
