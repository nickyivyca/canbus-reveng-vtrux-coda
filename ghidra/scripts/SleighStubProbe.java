// SleighStubProbe.java
// Probe every Continental NOP-stub opcode against whatever SuperH4 SLEIGH is
// currently installed, and report what that spec decodes each one as.
//
// Run it against an UNPATCHED (stock) SuperH4.sinc: every opcode that still
// decodes to a real instruction is one the stub is shadowing, i.e. the stub
// silently deletes a valid SH-4 instruction from the DLCM disassembly.
// 0x404C (`shad r4,r0`) is the first word of the SecurityAccess handler at
// 0x80079490 and is stubbed as nop_404C -- which is how this was found.
//
// Input program: sleigh_probe.bin, generated by
//   projects/coda/notes/dlcm/artifacts/sleigh_stub_shadow_probe.py 1
// One 4-byte slot per opcode: the opcode word followed by 0x0009 (nop), so
// each slot decodes standalone.
//
// Output path is the first script argument; defaults to
// ~/ghidra-projects/dlcm_export/sleigh_stub_probe.txt
//
// Run: analyzeHeadless <projdir> sleigh_probe -import sleigh_probe.bin \
//        -processor SuperH4:BE:32:default -noanalysis -overwrite \
//        -postScript SleighStubProbe.java -scriptPath <repo>/ghidra/scripts
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.mem.*;
import java.io.*;

public class SleighStubProbe extends GhidraScript {

    @Override
    public void run() throws Exception {
        String outPath = System.getProperty("user.home")
                + "/ghidra-projects/dlcm_export/sleigh_stub_probe.txt";
        String[] args = getScriptArgs();
        if (args.length > 0 && args[0].length() > 0) outPath = args[0];

        PrintWriter out = new PrintWriter(new FileWriter(outPath));
        Listing listing = currentProgram.getListing();
        Memory mem = currentProgram.getMemory();
        AddressSpace as = currentProgram.getAddressFactory().getDefaultAddressSpace();

        Address lo = mem.getMinAddress();
        Address hi = mem.getMaxAddress();
        long size = hi.getOffset() - lo.getOffset() + 1;
        int slots = (int) (size / 4);

        out.println("=== SLEIGH stub probe ===");
        out.println("program : " + currentProgram.getName()
                + "  lang=" + currentProgram.getLanguageID());
        out.println("memory  : " + lo + " .. " + hi + "  (" + slots + " slots)");
        out.println("A decode result other than '-' means the installed spec");
        out.println("decodes this opcode, so a nop_ stub for it is shadowing it.");
        out.println();

        int decodedCount = 0;
        for (int i = 0; i < slots; i++) {
            Address slot = lo.add(i * 4L);
            byte[] b = new byte[2];
            mem.getBytes(slot, b);
            int opcode = ((b[0] & 0xFF) << 8) | (b[1] & 0xFF);

            // Clear the whole listing each time so a previous slot's flow
            // (branches, delay slots) cannot influence this one.
            clearListing(lo, hi);
            try {
                disassemble(slot);
            } catch (Exception e) {
                // fall through; instruction will be null
            }
            Instruction ins = listing.getInstructionAt(slot);
            String text = "-";
            if (ins != null) {
                text = ins.toString();
                // A stub decodes as its own constructor name; that means the
                // patched spec is installed, not the stock one.
                decodedCount++;
            }
            out.printf("SLOT %08X opcode %04X -> %s%n", slot.getOffset(), opcode, text);
        }

        out.println();
        out.printf("decoded %d of %d slots%n", decodedCount, slots);
        out.flush();
        out.close();
        println("Done. Output: " + outPath + "  (" + decodedCount + "/" + slots + " decoded)");
    }
}
