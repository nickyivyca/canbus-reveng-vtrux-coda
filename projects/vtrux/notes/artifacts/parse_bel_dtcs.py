def parse_dtc_list(raw):
    """Parse DTC list, skipping 0xAA separator bytes. Returns list of (dtc_int, status)."""
    # First byte is status availability mask
    avail_mask = raw[0]
    print(f"Status availability mask: 0x{avail_mask:02X}")
    dtcs = []
    idx = 1
    while idx < len(raw):
        if raw[idx] == 0xAA:
            idx += 1
            continue
        if idx + 4 > len(raw):
            break
        b0, b1, b2, st = raw[idx], raw[idx+1], raw[idx+2], raw[idx+3]
        dtc = (b0 << 16) | (b1 << 8) | b2
        dtcs.append((dtc, st))
        idx += 4
    return dtcs

dtcs = parse_dtc_list(RAW)

# Group by prefix byte (first byte = fault category)
from collections import defaultdict
groups = defaultdict(list)
for dtc, st in dtcs:
    prefix = (dtc >> 16) & 0xFF
    groups[prefix].append((dtc, st))

print(f"\nTotal DTCs parsed: {len(dtcs)}")
print(f"Unique fault categories (prefix byte): {sorted(f'0x{p:02X}' for p in groups)}")
print()

status_names = {
    0x00: "no-status",
    0x2F: "stored+pending+confirmed+cleared",
    0x50: "stored+confirmed",
}

print("DTC list by category:")
for prefix in sorted(groups.keys()):
    entries = groups[prefix]
    statuses = set(st for _, st in entries)
    status_str = "/".join(f"0x{s:02X}" for s in sorted(statuses))
    print(f"\n  0x{prefix:02X}xx ({len(entries)} faults, status={status_str}):")
    for dtc, st in entries:
        st_name = status_names.get(st, f"0x{st:02X}")
        print(f"    0x{dtc:06X}  st={st_name}")
